    unit = "м" if p["kind"] in ("pipe", "insul") else "шт"
    if p["kind"] in FIT or key.startswith(("Мфт", "Пркл")):
        qty = zap(qty)
    m(p["name"], p["art"], qty, p["price"], p["src"], unit)


